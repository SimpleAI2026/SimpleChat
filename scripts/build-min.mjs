#!/usr/bin/env node
/**
 * Bundle @simplechat/element + @simplechat/core (+ marked) into one minified ESM.
 *
 * Usage:
 *   yarn build:min
 *   yarn build:min --no-copy   # skip sibling vendor copies
 *
 * Output:
 *   dist/simplechat.min.js
 *   ../SimpleMind/src/vendor/simplechat/simplechat.min.js       (default copy)
 *   ../SimpleExcalidraw/src/vendor/simplechat/simplechat.min.js (default copy)
 */
import * as esbuild from 'esbuild';
import { cpSync, mkdirSync, existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'scripts/browser-entry.ts');
const outDir = join(root, 'dist');
const outfile = join(outDir, 'simplechat.min.js');
const noCopy = process.argv.includes('--no-copy');

const vendors = [
  {
    label: 'SimpleMind',
    dir: join(root, '../SimpleMind/src/vendor/simplechat'),
    sibling: join(root, '../SimpleMind'),
    readme: [
      '# Vendored SimpleChat browser build',
      '',
      'Generated by SimpleChat `yarn build:min` (do not edit by hand).',
      '',
      'Rebuild + copy from SimpleChat repo:',
      '',
      '```bash',
      'cd ../SimpleChat && yarn build:min',
      '```',
      '',
      'Or build only:',
      '',
      '```bash',
      'cd ../SimpleChat && yarn build:min --no-copy',
      'cp dist/simplechat.min.js ../SimpleMind/src/vendor/simplechat/simplechat.min.js',
      '```',
      '',
      'The ESM side-effect registers `<simple-chat>` and exports width helpers',
      '(`loadSidebarWidth`, `clampSidebarWidth`, `SC_WIDTH_*`, …).',
      '',
    ].join('\n'),
  },
  {
    label: 'SimpleExcalidraw',
    dir: join(root, '../SimpleExcalidraw/src/vendor/simplechat'),
    sibling: join(root, '../SimpleExcalidraw'),
    readme: [
      '# Vendored SimpleChat browser build',
      '',
      '由 SimpleChat `yarn build:min` 生成（请勿手工编辑 min.js）。',
      '',
      '重建并拷贝：',
      '',
      '```bash',
      'cd ../SimpleChat && yarn build:min',
      '```',
      '',
      'Or build only:',
      '',
      '```bash',
      'cd ../SimpleChat && yarn build:min --no-copy',
      'cp dist/simplechat.min.js ../SimpleExcalidraw/src/vendor/simplechat/simplechat.min.js',
      '```',
      '',
      '该 ESM 副作用会注册 `<simple-chat>`，并导出宽度辅助函数（`loadSidebarWidth`、`clampSidebarWidth`、`SC_WIDTH_*` 等）。',
      '',
      '本仓库**不使用** npm portal / `@simplechat/*` 包，仅 vendor 此文件。',
      '',
    ].join('\n'),
  },
];

mkdirSync(outDir, { recursive: true });

await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  outfile,
  sourcemap: false,
  logLevel: 'info',
  // Resolve workspace packages from source; mark nothing external so marked is inlined.
});

const sizeKb = (await import('node:fs')).statSync(outfile).size / 1024;
console.log(`Wrote ${outfile} (${sizeKb.toFixed(1)} KiB)`);

if (!noCopy) {
  for (const v of vendors) {
    if (!existsSync(v.sibling)) {
      console.warn(
        `${v.label} sibling not found; skip vendor copy. Re-run with paths available or copy manually:`,
      );
      console.warn(
        `  cp ${outfile} <${v.label}>/src/vendor/simplechat/simplechat.min.js`,
      );
      continue;
    }
    mkdirSync(v.dir, { recursive: true });
    const out = join(v.dir, 'simplechat.min.js');
    cpSync(outfile, out);
    writeFileSync(join(v.dir, 'README.md'), v.readme, 'utf8');
    console.log(`Copied → ${out}`);
  }
}
