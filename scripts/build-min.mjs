#!/usr/bin/env node
/**
 * Bundle @simplechat/element + @simplechat/core (+ marked) into one minified ESM.
 *
 * Usage:
 *   yarn build:min
 *   yarn build:min --no-copy   # skip SimpleMind vendor copy
 *
 * Output:
 *   dist/simplechat.min.js
 *   ../SimpleMind/src/vendor/simplechat/simplechat.min.js  (default copy)
 */
import * as esbuild from 'esbuild';
import { cpSync, mkdirSync, existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'scripts/browser-entry.ts');
const outDir = join(root, 'dist');
const outfile = join(outDir, 'simplechat.min.js');
const mindVendorDir = join(root, '../SimpleMind/src/vendor/simplechat');
const mindOut = join(mindVendorDir, 'simplechat.min.js');
const noCopy = process.argv.includes('--no-copy');

mkdirSync(outDir, { recursive: true });

await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  minify: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  outfile,
  sourcemap: false,
  logLevel: 'info',
  // Resolve workspace packages from source; mark nothing external so marked is inlined.
});

const sizeKb = (await import('node:fs')).statSync(outfile).size / 1024;
console.log(`Wrote ${outfile} (${sizeKb.toFixed(1)} KiB)`);

if (!noCopy) {
  if (!existsSync(join(root, '../SimpleMind'))) {
    console.warn('SimpleMind sibling not found; skip vendor copy. Re-run with paths available or copy manually:');
    console.warn(`  cp ${outfile} <SimpleMind>/src/vendor/simplechat/simplechat.min.js`);
  } else {
    mkdirSync(mindVendorDir, { recursive: true });
    cpSync(outfile, mindOut);
    writeFileSync(
      join(mindVendorDir, 'README.md'),
      [
        '# Vendored SimpleChat browser build',
        '',
        'Generated by SimpleChat `yarn build:min` (do not edit by hand).',
        '',
        'Rebuild + copy from SimpleChat repo:',
        '',
        '```bash',
        'cd ../SimpleChat && yarn build:min',
        '```',
        '',
        'Or build only:',
        '',
        '```bash',
        'cd ../SimpleChat && yarn build:min --no-copy',
        'cp dist/simplechat.min.js ../SimpleMind/src/vendor/simplechat/simplechat.min.js',
        '```',
        '',
        'The ESM side-effect registers `<simple-chat>` and exports width helpers',
        '(`loadSidebarWidth`, `clampSidebarWidth`, `SC_WIDTH_*`, …).',
        '',
      ].join('\n'),
      'utf8',
    );
    console.log(`Copied → ${mindOut}`);
  }
}
